// Generate the right-to-left tables used by Arabic shaping and bidi reordering, as GL JS does in
// build/generate-unicode-data.ts. Usage: node scripts/gen-rtl-data.ts path/to/ucd > crates/core/src/symbol/rtl_data.rs
// The directory holds these files of https://www.unicode.org/Public/<UNICODE>/ucd/, side by side:
// UnicodeData.txt, Scripts.txt, BidiMirroring.txt, extracted/DerivedJoiningType.txt, extracted/DerivedBidiClass.txt.
import {readFileSync} from 'node:fs';
import {join} from 'node:path';

const UNICODE = '17.0.0';
const dir = process.argv[2];

/** Data lines of a UCD file, as `[first, last, fields...]`. */
function rows(file: string): Array<[number, number, string[]]> {
    const out: Array<[number, number, string[]]> = [];
    for (const raw of readFileSync(join(dir, file), 'utf8').split('\n')) {
        const line = raw.split('#')[0].trim();
        if (!line) continue;
        const [cps, ...fields] = line.split(';').map(s => s.trim());
        const [a, b] = cps.split('..').map(s => parseInt(s, 16));
        out.push([a, b ?? a, fields]);
    }
    return out;
}

/** Sorted code points as inclusive ranges. */
function toRanges(cps: Iterable<number>): Array<[number, number]> {
    const ranges: Array<[number, number]> = [];
    for (const cp of [...new Set(cps)].sort((a, b) => a - b)) {
        const last = ranges[ranges.length - 1];
        if (last && last[1] + 1 === cp) last[1] = cp;
        else ranges.push([cp, cp]);
    }
    return ranges;
}

const hex = (cp: number) => `0x${cp.toString(16).toUpperCase().padStart(4, '0')}`;

/** Items packed onto lines of at most 120 columns. */
function pack(items: string[]): string {
    const lines: string[] = [];
    let line = '   ';
    for (const item of items) {
        if (line.length + item.length + 2 > 120) {
            lines.push(line);
            line = '   ';
        }
        line += ` ${item},`;
    }
    if (line.trim()) lines.push(line);
    return lines.join('\n');
}

// Joining types of the Arabic blocks and the two joiners (GL JS `arabicBlocks`).
const ARABIC_BLOCKS = [
    [0x0600, 0x06ff],
    [0x0750, 0x077f],
    [0x0870, 0x089f],
    [0x08a0, 0x08ff],
    [0xfb50, 0xfdff],
    [0xfe70, 0xfeff],
    [0x200c, 0x200d],
];
const isArabic = (cp: number) => ARABIC_BLOCKS.some(([a, b]) => cp >= a && cp <= b);
const joining: Array<[number, number, string]> = [];
for (const [a, b, [type]] of rows('DerivedJoiningType.txt')) {
    if (type === 'U') continue;
    for (let cp = a; cp <= b; cp++) {
        if (!isArabic(cp)) continue;
        const last = joining[joining.length - 1];
        if (last && last[1] + 1 === cp && last[2] === type) last[1] = cp;
        else joining.push([cp, cp, type]);
    }
}
joining.sort((x, y) => x[0] - y[0]);

// Presentation forms (`<isolated> 0628`) and lam-alef ligatures, from the decompositions of FB50..FEFF.
// A mark's forms decompose onto a carrier: space for isolated, tatweel for medial.
const SHAPES = ['isolated', 'final', 'initial', 'medial'];
const CARRIERS = new Set([0x0020, 0x0640]);
const forms = new Map<number, number[]>();
const ligatures = new Map<number, number[]>();
for (const [cp, , fields] of rows('UnicodeData.txt')) {
    if (cp < 0xfb50 || cp > 0xfeff) continue;
    const m = /^<(\w+)> (.+)$/.exec(fields[4]);
    if (!m || !SHAPES.includes(m[1])) continue;
    const shape = SHAPES.indexOf(m[1]);
    const bases = m[2].split(' ').map(s => parseInt(s, 16));
    if (bases.length === 1 || (bases.length === 2 && CARRIERS.has(bases[0]))) {
        const base = bases[bases.length - 1];
        const entry = forms.get(base) ?? [0, 0, 0, 0];
        entry[shape] = cp;
        forms.set(base, entry);
    } else if (cp >= 0xfef5 && cp <= 0xfefc && bases[0] === 0x0644 && shape < 2) {
        const entry = ligatures.get(bases[1]) ?? [0, 0];
        entry[shape] = cp;
        ligatures.set(bases[1], entry);
    }
}

// Every script (but Common and Unknown) with a character of bidi class R or AL (GL JS `isInRTLScript`).
const rtlClass = new Set<number>();
for (const [a, b, [cls]] of rows('DerivedBidiClass.txt')) {
    if (cls === 'R' || cls === 'AL') for (let cp = a; cp <= b; cp++) rtlClass.add(cp);
}
const scripts = new Map<string, number[]>();
for (const [a, b, [script]] of rows('Scripts.txt')) {
    const cps = scripts.get(script) ?? [];
    for (let cp = a; cp <= b; cp++) cps.push(cp);
    scripts.set(script, cps);
}
const rtl: number[] = [];
for (const [script, cps] of scripts) {
    if (script !== 'Common' && script !== 'Unknown' && cps.some(cp => rtlClass.has(cp))) rtl.push(...cps);
}

// Bidi_Mirroring_Glyph, every pair the file lists (as bidi-js does).
const mirrored = rows('BidiMirroring.txt').map(([a, , [b]]) => [a, parseInt(b, 16)]);
mirrored.sort((x, y) => x[0] - y[0]);

process.stdout.write(`// Generated by scripts/gen-rtl-data.ts from the Unicode ${UNICODE} character database. Do not edit.

use super::arabic::Joining::{self, ${[...new Set(joining.map(j => j[2]))].sort().join(', ')}};

/// \`Joining_Type\` of the Arabic blocks and the joiners, as \`(first, last, type)\`; \`U\` elsewhere.
#[rustfmt::skip]
pub const JOINING_TYPES: &[(u32, u32, Joining)] = &[
${pack(joining.map(([a, b, t]) => `(${hex(a)}, ${hex(b)}, ${t})`))}
];

/// Presentation forms of each letter or mark: \`(base, [isolated, final, initial, medial])\`, 0 where none.
#[rustfmt::skip]
pub const PRESENTATION_FORMS: &[(u16, [u16; 4])] = &[
${pack([...forms].sort((x, y) => x[0] - y[0]).map(([b, f]) => `(${hex(b)}, [${f.map(hex).join(', ')}])`))}
];

/// Lam followed by this alef is written as one ligature: \`(alef, [isolated, final])\`.
#[rustfmt::skip]
pub const LAM_ALEF: &[(u16, [u16; 2])] = &[
${pack([...ligatures].sort((x, y) => x[0] - y[0]).map(([b, f]) => `(${hex(b)}, [${f.map(hex).join(', ')}])`))}
];

/// Scripts written right to left, as inclusive ranges.
#[rustfmt::skip]
pub const RTL_SCRIPTS: &[(u32, u32)] = &[
${pack(toRanges(rtl).map(([a, b]) => `(${hex(a)}, ${hex(b)})`))}
];

/// \`Bidi_Mirroring_Glyph\`: \`(character, mirrored)\`.
#[rustfmt::skip]
pub const MIRRORED: &[(u32, u32)] = &[
${pack(mirrored.map(([a, b]) => `(${hex(a)}, ${hex(b)})`))}
];
`);
